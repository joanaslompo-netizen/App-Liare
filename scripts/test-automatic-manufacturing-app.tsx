import { workspaceStorage as storage } from '../src/utils/workspaceStorage';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
import assert from 'node:assert/strict';
import { autoMaterials, autoProducts } from './automaticManufacturingFixtures';
import { DEFAULT_SETTINGS } from '../src/utils/storage';
const dom=new JSDOM('<!doctype html><div id="root"></div>',{url:'http://localhost/'});
for(const key of ['window','document','HTMLElement','HTMLInputElement','HTMLSelectElement','Event','MouseEvent','localStorage'])Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
const alerts:string[]=[];
Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true,alert:(message:string)=>alerts.push(message),confirm:()=>true,requestAnimationFrame:(callback:()=>void)=>setTimeout(callback,0),cancelAnimationFrame:clearTimeout});
dom.window.confirm=()=>true;dom.window.HTMLElement.prototype.scrollIntoView=()=>{};dom.window.scrollTo=()=>{};
storage.setItem('atelie_workspace_finance_v1',JSON.stringify({materials:autoMaterials,products:autoProducts,purchases:[],productions:[],sales:[],customers:[],suppliers:[],paymentMethods:[],settings:DEFAULT_SETTINGS,todos:[],projects:[],finance:{version:1,entries:[],bills:[]},stockMovements:[]}));
const {createRoot}=await import('react-dom/client');const {default:App}=await import('../src/App');
let root=createRoot(document.querySelector('#root')!);
const saved=()=>JSON.parse(storage.getItem('atelie_workspace_finance_v1')!);
async function button(text:string){const element=[...document.querySelectorAll('button')].find(node=>node.textContent?.trim()===text);assert(element,text);await act(async()=>element.click());}
await act(async()=>root.render(<App/>));await button('Registrar produção');
const search=document.querySelector<HTMLInputElement>('input[id$="-model"]')!;assert(search);await act(async()=>search.focus());
const option=[...document.querySelectorAll<HTMLElement>('[role="option"]')].find(node=>node.dataset.modelId==='product:candle');assert(option);await act(async()=>option.click());
assert(document.body.textContent?.includes('fabricar e consumir automaticamente'));
await button('Iniciar todas as produções');
assert.equal(alerts.length,0,alerts.join('; '));
assert.equal(saved().materials.find((material:any)=>material.id==='wax').currentStock,64);
assert.equal(saved().materials.find((material:any)=>material.id==='blend').currentStock,0);
assert.equal(saved().products.find((product:any)=>product.id==='decoration').currentStock,0);
assert.equal(saved().products.find((product:any)=>product.id==='candle').currentStock,1);
assert.equal(saved().productions[0].automaticManufacturing.length,2);
assert(saved().stockMovements.some((movement:any)=>movement.reason==='Produção automática'));
await act(async()=>root.unmount());root=createRoot(document.querySelector('#root')!);await act(async()=>root.render(<App/>));
assert.equal(saved().materials.find((material:any)=>material.id==='wax').currentStock,64);
await act(async()=>(document.querySelector('[aria-label="Abrir atalhos rápidos"]') as HTMLElement).click());await button('Produções');
await act(async()=>(document.querySelector('#production-tab-completed') as HTMLElement).click());await button('Excluir e estornar');
for(const material of autoMaterials)assert.equal(saved().materials.find((value:any)=>value.id===material.id).currentStock,material.currentStock);
for(const product of autoProducts)assert.equal(saved().products.find((value:any)=>value.id===product.id).currentStock,product.currentStock);
assert.equal(saved().productions.length,0);
assert.equal(alerts.length,0,alerts.join('; '));await act(async()=>root.unmount());
console.log('PASS app: produção com componentes faltantes fabrica automaticamente, baixa ingredientes, preserva ao reabrir e estorna os insumos reais.');
process.exit(0);
