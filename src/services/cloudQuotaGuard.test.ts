import assert from 'node:assert/strict';
import { CloudQuotaGuard, CloudQuotaPausedError, nextQuotaResetAt } from './cloudQuotaGuard';
const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); }, removeItem: (key: string) => { values.delete(key); } };
let now = Date.parse('2026-10-22T17:00:00Z');
const first = new CloudQuotaGuard(storage, () => now);
first.record('owner', Object.assign(new Error('Free daily write units per project'), { code: 'resource-exhausted' }), 'write');
assert.throws(() => first.assertAllowed('owner', 'write'), CloudQuotaPausedError);
first.assertAllowed('owner', 'read');
first.assertAllowed('another-owner', 'write');
const dailyUntil=first.retryAt('owner');
first.record('owner',{code:'resource-exhausted',message:'Temporary capacity'},'read');
assert.equal(first.retryAt('owner'),dailyUntil,'A short temporary limit cannot shorten a known daily pause');
const reopened = new CloudQuotaGuard(storage, () => now);
assert.throws(() => reopened.assertAllowed('owner', 'write'), CloudQuotaPausedError, 'Reload/another tab retains the quota pause');
assert.equal(new Date(nextQuotaResetAt(now)).toISOString(), '2026-10-23T07:01:00.000Z');
assert.equal(new Date(nextQuotaResetAt(Date.parse('2026-12-22T17:00:00Z'))).toISOString(), '2026-12-23T08:01:00.000Z');
now = Date.parse('2026-10-23T07:01:01Z');
reopened.assertAllowed('owner', 'write');
assert.equal(values.size, 0, 'Quota renewal releases access automatically');
first.record('owner', { code: 'unavailable' }, 'write');
first.assertAllowed('owner', 'write');
console.log('PASS quota pause: shared across tabs/reloads, scoped by user and operation, DST-aware expiry and no pause for transient errors.');
